"""Read-only Linux mount discovery and managed SnapRAID configuration planning."""
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import uuid

MODES={'single':1,'double':2,'triple':3}


def decode_mount(value):
    return re.sub(r'\\([0-7]{3})',lambda m:chr(int(m.group(1),8)),value)


def physical_disks(device):
    """Fail closed if container sysfs cannot identify physical failure domains."""
    target=Path('/sys/dev/block')/device
    if not target.exists():return []
    def leaves(path,visited):
        path=path.resolve()
        if str(path) in visited:return []
        visited.add(str(path))
        if (path/'partition').exists():path=path.parent
        slaves=path/'slaves'
        children=list(slaves.iterdir()) if slaves.is_dir() else []
        if children:
            result=[]
            for child in children:result+=leaves(child,visited)
            return sorted(set(result))
        if path.name.startswith(('loop','ram','zram','dm-','md')):return []
        return [str(path)]
    return leaves(target,set())


def inventory(bases):
    mountinfo=Path('/proc/self/mountinfo')
    if not mountinfo.exists():return []
    rows=[]
    for line in mountinfo.read_text().splitlines():
        left,separator,right=line.partition(' - ')
        if not separator:continue
        fields=left.split();tail=right.split()
        if len(fields)<6 or len(tail)<2:continue
        path=Path(decode_mount(fields[4]))
        if str(path)=='/' or not any(path==base or base in path.parents for base in bases):continue
        try:
            usage=shutil.disk_usage(path);stat=path.stat()
            device=f'{os.major(stat.st_dev)}:{os.minor(stat.st_dev)}'
            parents=physical_disks(device)
            readonly='ro' in fields[5].split(',') or not os.access(path,os.W_OK)
            key='|'.join([device,decode_mount(tail[1]),decode_mount(fields[3])])
            identifier=hashlib.sha256((key+'|'+str(path)).encode()).hexdigest()[:24]
            reason=''
            if len(parents)!=1:reason='无法确认独立物理磁盘，需在 PVE / 容器中提供设备识别信息'
            elif readonly:reason='磁盘只读，不能保存校验或 content 元数据'
            if any((path/name).exists() for name in ('snapraid.content','snapraid.parity','snapraid.2-parity','snapraid.3-parity')):reason='发现已有 SnapRAID 元数据，需使用既有阵列迁移流程，不能按新方案覆盖'
            if any(c in str(path) for c in '\n\r\x00,#'):reason='挂载路径包含当前配置生成器不支持的字符'
            rows.append({'id':identifier,'path':str(path),'device':decode_mount(tail[1]),'filesystem':tail[0],
                         'device_key':key,'physical_disks':parents,'total':usage.total,'free':usage.free,
                         'readonly':readonly,'selectable':not reason,'reason':reason})
        except OSError:continue
    return rows


def build_plan(request,disks):
    mode=request.get('mode');level=MODES.get(mode)
    if level is None:raise ValueError('请选择单、双或三校验模式')
    entries=request.get('disks')
    if not isinstance(entries,list) or not 2<=len(entries)<=64:raise ValueError('请选择数据盘与校验盘')
    available={d['id']:d for d in disks};selected=[];ids=set();physical=set()
    for item in entries:
        if not isinstance(item,dict):raise ValueError('磁盘选项无效')
        disk=available.get(item.get('id'))
        if not disk or not disk['selectable']:raise ValueError('所选磁盘不可用，请刷新磁盘列表')
        if disk['id'] in ids:raise ValueError('不能重复选择磁盘')
        domains=set(disk['physical_disks'])
        if physical & domains:raise ValueError('同一物理盘的分区或绑定目录不能作为独立磁盘')
        role=item.get('role')
        if role not in ('data','parity'):raise ValueError('磁盘角色无效')
        if type(item.get('content',True)) is not bool:raise ValueError('content 选项无效')
        ids.add(disk['id']);physical.update(domains)
        selected.append(dict(disk,role=role,content=item.get('content',True)))
    data=[d for d in selected if d['role']=='data'];parity=[d for d in selected if d['role']=='parity']
    if not data or len(parity)!=level:raise ValueError(f'此模式需要至少一块数据盘和 {level} 块校验盘')
    if sum(d['content'] for d in selected)<level+1:raise ValueError('content 副本数至少应为校验级别 + 1，并分布在独立磁盘')
    for p in parity:
        if p['total']<max(d['total'] for d in data):raise ValueError('每块校验盘容量须不小于最大数据盘')
        if p['free']<max(d['total']-d['free'] for d in data):raise ValueError('校验盘剩余空间不足，无法容纳当前已用数据的保守估算')
    lines=['# Generated by PhotoSync. Do not edit; use disk roles in the UI.']
    for index,p in enumerate(parity,1):
        directive='parity' if index==1 else f'{index}-parity'
        filename='snapraid.parity' if index==1 else f'snapraid.{index}-parity'
        lines.append(f'{directive} {p["path"]}/{filename}')
    for disk in selected:
        if disk['content']:lines.append(f'content {disk["path"]}/snapraid.content')
    for index,d in enumerate(data,1):lines.append(f'data d{index} {d["path"]}/')
    lines+=['exclude *.part','exclude *.partial','exclude *.tmp','exclude *.crdownload']
    return {'mode':mode,'parity_level':level,'disks':selected,'configuration':'\n'.join(lines)+'\n',
            'interval_seconds':max(30,min(86400,int(request.get('interval_seconds',3600)))),'state':'planned','message':'方案已生成，尚未执行首次同步，数据尚未建立校验保护'}
